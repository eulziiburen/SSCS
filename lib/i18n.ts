// Known badge values get a translation; anything custom from the admin is shown as typed
const BADGES_EN: Record<string, string> = { ОНЦЛОХ: "FEATURED", ЭРЭЛТТЭЙ: "POPULAR", ХЯМДРАЛТАЙ: "ON SALE", ШИНЭ: "NEW" };

export function badgeLabel(badge: string, locale: Locale) {
  return locale === "en" ? BADGES_EN[badge.toUpperCase()] ?? badge : badge;
}
